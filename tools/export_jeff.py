# Bakes Jeff's rig (rigid block parts on bones) and scare animation into a Luau ModuleScript.
# Run: blender -b art/monsters/jeff/jeff.blend --python tools/export_jeff.py -- src/ReplicatedStorage/Shared/JeffAnim.luau
import bpy, sys, math
from mathutils import Matrix, Vector

OUT = sys.argv[sys.argv.index("--") + 1]
S = 1.1                         # studs per metre
STEP = 2                        # sample every 2nd frame (15 fps)
C = Matrix(((-1, 0, 0), (0, 0, 1), (0, 1, 0)))  # Blender Z-up, facing -Y  ->  Roblox Y-up, facing -Z

sc = bpy.context.scene
rig = bpy.data.objects["Jeff_Rig"]
bones = [b.name for b in rig.data.bones]

def srgb(c):
    return [round(max(0, min(1, v)) ** (1 / 2.2) * 255) for v in c[:3]]

def color(o):
    m = o.active_material
    if not m:
        return [200, 200, 200]
    if m.use_nodes and m.node_tree.nodes.get("Principled BSDF"):
        return srgb(m.node_tree.nodes["Principled BSDF"].inputs["Base Color"].default_value)
    return srgb(m.diffuse_color)

def bone_world(name):
    return rig.matrix_world @ rig.pose.bones[name].matrix

sc.frame_set(sc.frame_start)
parts = []
for o in bpy.data.objects:
    if o.parent != rig or o.type != 'MESH' or not o.parent_bone:
        continue
    lo = [min(c[i] for c in o.bound_box) for i in range(3)]
    hi = [max(c[i] for c in o.bound_box) for i in range(3)]
    loc, rot, sca = o.matrix_world.decompose()
    size = [(hi[i] - lo[i]) * sca[i] for i in range(3)]
    centre = o.matrix_world @ Vector([(lo[i] + hi[i]) / 2 for i in range(3)])
    part_m = Matrix.LocRotScale(centre, rot, None)
    bl, br, bs = bone_world(o.parent_bone).decompose()
    off = Matrix.LocRotScale(bl, br, None).inverted() @ part_m
    shape = "Block"
    if len(o.data.vertices) > 8:
        thin = min(range(3), key=lambda i: size[i])
        if size[thin] < 0.3 * max(size):
            shape = "Cylinder"  # flat disc: Roblox cylinders run along X, so turn the thin axis onto X
            if thin == 2:
                off = off @ Matrix.Rotation(math.pi / 2, 4, 'Y'); size = [size[2], size[1], size[0]]
            elif thin == 1:
                off = off @ Matrix.Rotation(math.pi / 2, 4, 'Z'); size = [size[1], size[0], size[2]]
        else:
            shape = "Ball"
    q = off.to_quaternion()
    t = off.translation
    parts.append((o.name, o.parent_bone, [v * S for v in size], [t.x * S, t.y * S, t.z * S], [q.x, q.y, q.z, q.w], color(o), shape))

frames = []
for f in range(sc.frame_start, sc.frame_end + 1, STEP):
    sc.frame_set(f)
    row = []
    for b in bones:
        l, r, s = bone_world(b).decompose()
        p = C @ l * S
        q = (C @ r.to_matrix()).to_quaternion()
        row.append([p.x, p.y, p.z, q.x, q.y, q.z, q.w, s.x, s.y, s.z])
    frames.append(row)

def n(v):
    return ("%.3f" % v).rstrip("0").rstrip(".") if v != 0 else "0"

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("-- Generated by tools/export_jeff.py from art/monsters/jeff/jeff.blend. Do not edit by hand.\n")
    fh.write("return {\n\tfps = %d,\n\tbones = {%s},\n\tparts = {\n" % (sc.render.fps / STEP, ", ".join('"%s"' % b for b in bones)))
    for name, bone, size, pos, q, col, shape in parts:
        fh.write('\t\t{"%s", "%s", {%s}, {%s}, {%s}, {%s}, "%s"},\n' % (name, bone, ", ".join(map(n, size)), ", ".join(map(n, pos)), ", ".join(map(n, q)), ", ".join(map(str, col)), shape))
    fh.write("\t},\n\tframes = {\n")
    for row in frames:
        fh.write("\t\t{" + ", ".join("{" + ", ".join(map(n, b)) + "}" for b in row) + "},\n")
    fh.write("\t},\n}\n")
print("EXPORTED", len(parts), "parts", len(frames), "frames")
